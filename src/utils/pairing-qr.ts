export interface ParsedPairingQrPayload {
  valid: boolean;
  pairingKey?: string;
  pairingToken?: string;
  email?: string;
  issuer?: string;
  error?: string;
}

const PAIRING_KEY_PATTERN = /^VG-[A-Z0-9]{4}-[A-Z0-9]{4}$/i;
const RAW_TOKEN_PATTERN = /^[A-Za-z0-9_-]{12,128}$/;

/**
 * Parses QR code payloads scanned from Frontend Vanguard Mobile Integration modal.
 * Supports JSON payloads (`{ pairingKey, pairingToken, email, issuer }`),
 * URL/deep-link query parameters, and direct `VG-XXXX-XXXX` / pairing token strings.
 * Rejects `otpauth://` URIs so 2FA account QR codes are not confused with device pairing.
 */
export function parseDevicePairingQrPayload(raw: string): ParsedPairingQrPayload {
  const trimmed = (raw ?? '').trim();
  if (!trimmed) {
    return { valid: false, error: 'Scanned QR code is empty.' };
  }

  if (/^otpauth:\/\//i.test(trimmed)) {
    return {
      valid: false,
      error: 'This is a 2FA Authenticator QR code (otpauth://). Scan the Mobile Integration QR in Account Security instead.',
    };
  }

  // 1. JSON payload generated by Vanguard Backend (/oauth/devices/pairing-session)
  if (trimmed.startsWith('{')) {
    try {
      const parsed = JSON.parse(trimmed) as Record<string, unknown>;
      const pairingKey = typeof parsed['pairingKey'] === 'string' ? parsed['pairingKey'].trim().toUpperCase() : undefined;
      const pairingToken = typeof parsed['pairingToken'] === 'string' ? parsed['pairingToken'].trim() : undefined;
      const email = typeof parsed['email'] === 'string' ? parsed['email'].trim().toLowerCase() : undefined;
      const issuer = typeof parsed['issuer'] === 'string' ? parsed['issuer'].trim() : undefined;

      const resolvedKey = pairingKey || pairingToken;
      if (!resolvedKey || resolvedKey.length < 6) {
        return {
          valid: false,
          error: 'QR payload is missing a valid Vanguard pairing key or token.',
        };
      }

      return {
        valid: true,
        pairingKey: pairingKey || undefined,
        pairingToken: pairingToken || undefined,
        email,
        issuer,
      };
    } catch {
      return { valid: false, error: 'Scanned JSON QR code is malformed.' };
    }
  }

  // 2. Deep-link or URL with pairingKey / pairingToken / key / token query parameters
  if (trimmed.includes('://') && trimmed.includes('?')) {
    try {
      const url = new URL(trimmed);
      const keyParam = url.searchParams.get('pairingKey') ?? url.searchParams.get('key');
      const tokenParam = url.searchParams.get('pairingToken') ?? url.searchParams.get('token');
      const emailParam = url.searchParams.get('email');
      const issuerParam = url.searchParams.get('issuer');

      const pairingKey = keyParam ? keyParam.trim().toUpperCase() : undefined;
      const pairingToken = tokenParam ? tokenParam.trim() : undefined;
      if ((pairingKey && pairingKey.length >= 6) || (pairingToken && pairingToken.length >= 6)) {
        return {
          valid: true,
          pairingKey,
          pairingToken,
          email: emailParam ? emailParam.trim().toLowerCase() : undefined,
          issuer: issuerParam ? issuerParam.trim() : undefined,
        };
      }
      return {
        valid: false,
        error: 'URL QR code does not contain a pairingKey or pairingToken parameter.',
      };
    } catch {
      return { valid: false, error: 'Malformed QR URL.' };
    }
  }

  // 3. Plaintext VG-XXXX-XXXX key or pairing token
  if (PAIRING_KEY_PATTERN.test(trimmed)) {
    return { valid: true, pairingKey: trimmed.toUpperCase() };
  }

  if (RAW_TOKEN_PATTERN.test(trimmed)) {
    return { valid: true, pairingToken: trimmed };
  }

  return {
    valid: false,
    error: 'Unrecognized QR format. Please scan the Vanguard Mobile Integration QR code.',
  };
}
